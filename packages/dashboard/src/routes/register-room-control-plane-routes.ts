  context.router.get("/rooms/:roomId/events", async (req, res) => {
    let unsubscribe: RoomControlPlaneLiveEventSubscriptionV1 | null = null;
    let unsubscribeTermination: (() => void) | null = null;
    let releaseActorConnection: (() => void) | null = null;
    let connectionLifetimeTimer: ReturnType<typeof setTimeout> | null = null;
    let heartbeat: ReturnType<typeof setInterval> | null = null;
    let closed = false;
    let terminationBeforeHeaders = false;
    let streamScope: RoomControlPlaneLiveEventScopeV1 | null = null;

    const cleanup = (): void => {
      if (closed) return;
      closed = true;
      if (heartbeat !== null) {
        clearInterval(heartbeat);
        heartbeat = null;
      }
      if (connectionLifetimeTimer !== null) {
        clearTimeout(connectionLifetimeTimer);
        connectionLifetimeTimer = null;
      }
      const closeSubscription = unsubscribe;
      unsubscribe = null;
      const closeTermination = unsubscribeTermination;
      unsubscribeTermination = null;
      try {
        closeSubscription?.();
      } catch {
        // Stream teardown is best-effort after a disconnected client.
      }
      try {
        closeTermination?.();
      } catch {
        // Stream teardown is best-effort after a disconnected client.
      }
      const release = releaseActorConnection;
      releaseActorConnection = null;
      release?.();
      req.off("close", cleanup);
      req.off("aborted", cleanup);
      res.off("close", cleanup);
    };

    const terminateStream = (code: "canonical_replay_invalid" | "stream_disconnected"): void => {
      let alertWrite: RoomSseWriteResult = "ok";
      if (streamScope !== null && !res.writableEnded && !res.destroyed) {
        alertWrite = writeRoomSse(res, "room.alert", {
          contractVersion: 1,
          type: "room_alert",
          scope: cloneScope(streamScope),
          alerts: [{
            code,
            severity: "critical",
            scope: cloneScope(streamScope),
            cursor: null,
            expectedStreamSequence: null,
            observedStreamSequence: null,
          }],
        });
      }
      cleanup();
      if (alertWrite === "backpressure") {
        if (!res.destroyed) res.destroy();
        return;
      }
      if (!res.writableEnded && !res.destroyed) res.end();
    };

    const terminateBackpressuredStream = (): void => {
      cleanup();
      if (!res.destroyed) res.destroy();
    };

    const terminateForLiveEventTermination = (rawSignal: unknown): void => {
      /*
      FNXC:RoomSseTermination 2026-07-19-19:45:
      The Engine's typed termination is authoritative. Once received, emit the
      validated connection degradation/disconnect and its sanitized alert, then
      close; do not leave a heartbeat-only stream behind.
      */
      if (closed) return;
      let termination: VerifiedRoomTerminationV1;
      try {
        termination = sanitizeTermination(rawSignal, streamScope!);
      } catch {
        if (!res.headersSent) {
          terminationBeforeHeaders = true;
          cleanup();
          return;
        }
        terminateStream("canonical_replay_invalid");
        return;
      }
      if (!res.headersSent) {
        terminationBeforeHeaders = true;
        cleanup();
        return;
      }
      const connectionWrite = writeRoomSse(res, "room.connection", {
        contractVersion: 1,
        type: "room_connection",
        scope: cloneScope(streamScope!),
        cursor: null,
        connection: {
          state: termination.connection.state,
          reason: termination.connectionReason,
          changedAt: termination.connection.changedAt,
        },
        alerts: [],
      });
      let alertWrite: RoomSseWriteResult = connectionWrite;
      if (connectionWrite === "ok") {
        alertWrite = writeRoomSse(res, "room.alert", {
          contractVersion: 1,
          type: "room_alert",
          scope: cloneScope(streamScope!),
          alerts: termination.alerts,
        });
      }
      cleanup();
      if (alertWrite === "backpressure") {
        if (!res.destroyed) res.destroy();
        return;
      }
      if (!res.writableEnded && !res.destroyed) res.end();
    };

    try {
      const params = parseOrThrow(roomParamsSchema, req.params);
      const query = parseOrThrow(liveEventQuerySchema, withoutTransportTokenQuery(req.query));
      const afterCursor = resolveEventCursor(req, query.cursor);
      const scope = await resolveScope({
        context,
        dependencies,
        request: req,
        access: "read",
        resource: "room",
        roomId: params.roomId,
        operation: "read",
      });
      streamScope = Object.freeze({ projectId: scope.projectId, roomId: params.roomId });
      releaseActorConnection = acquireRoomEventConnection(streamScope, scope.actorId);
      req.once("close", cleanup);
      req.once("aborted", cleanup);
      res.once("close", cleanup);
      const liveEventPort = await scope.port.openRoomEventCursor({
        projectId: scope.projectId,
        roomId: params.roomId,
      });
      if (
        !liveEventPort
        || typeof liveEventPort.reconnect !== "function"
        || typeof liveEventPort.subscribe !== "function"
        || typeof liveEventPort.subscribeTermination !== "function"
      ) {
        throw invalidEventPortResponse("ROOM_EVENT_PORT_UNAVAILABLE", "Room live event delivery is unavailable.");
      }
      if (closed) return;

      const deliveredByCursor = new Map<string, string>();
      const deliveredByEventId = new Map<string, string>();
      const deliveryHistory: Array<Readonly<{ cursor: string; eventId: string }>> = [];
      let lastSequence = afterCursor === null ? null : Number(afterCursor);
      let phase: "replaying" | "live" = "replaying";

      const rememberDelivery = (event: VerifiedRoomLiveEventV1, fingerprint: string): void => {
        deliveredByCursor.set(event.envelope.cursor, fingerprint);
        deliveredByEventId.set(event.envelope.eventId, event.envelope.cursor);
        deliveryHistory.push(Object.freeze({ cursor: event.envelope.cursor, eventId: event.envelope.eventId }));
        if (deliveryHistory.length <= ROOM_EVENT_DELIVERY_HISTORY_LIMIT) return;
        const oldest = deliveryHistory.shift();
        if (oldest === undefined) return;
        deliveredByCursor.delete(oldest.cursor);
        deliveredByEventId.delete(oldest.eventId);
      };

      const emitVerifiedEvent = (event: VerifiedRoomLiveEventV1): boolean => {
        const fingerprint = JSON.stringify([
          event.envelope.cursor,
          event.envelope.eventId,
          event.envelope.aggregateVersion,
          event.envelope.eventType,
          event.envelope.event,
        ]);
        const existingCursor = deliveredByCursor.get(event.envelope.cursor);
        const existingEventId = deliveredByEventId.get(event.envelope.eventId);
        if (existingCursor !== undefined || existingEventId !== undefined) {
          // FNXC:RoomSseReplayRace 2026-07-19-19:45: exact canonical replay/live overlap is benign.
          if (existingCursor === fingerprint && existingEventId === event.envelope.cursor) return true;
          terminateStream("canonical_replay_invalid");
          return false;
        }
        if (lastSequence !== null && event.envelope.sequence <= lastSequence) {
          terminateStream("canonical_replay_invalid");
          return false;
        }
        const writeResult = writeRoomSse(res, "room.event", {
          contractVersion: 1,
          type: "canonical_room_event",
          scope: cloneScope(event.scope),
          provenance: projectRoomSseEventProvenance(event),
          connection: {
            state: event.connection.state,
            reason: null,
            changedAt: event.connection.changedAt,
          },
          alerts: event.alerts,
        }, event.envelope.cursor);
        if (writeResult !== "ok") {
          if (writeResult === "backpressure") terminateBackpressuredStream();
          else terminateStream("stream_disconnected");
          return false;
        }
        rememberDelivery(event, fingerprint);
        lastSequence = event.envelope.sequence;
        return true;
      };

      const handleLiveNotification = (notification: unknown): void => {
        if (closed) return;
        try {
          const event = sanitizeNotification(notification, streamScope!);
          if (phase !== "live") return;
          emitVerifiedEvent(event);
        } catch {
          terminateStream("canonical_replay_invalid");
        }
      };

      const candidateUnsubscribe = liveEventPort.subscribe({
        ...streamScope,
        actorId: scope.actorId,
        holdUntilReplayWatermark: true,
        afterCursor,
      }, handleLiveNotification);
      if (typeof candidateUnsubscribe !== "function") {
        throw invalidEventPortResponse("ROOM_EVENT_PORT_INVALID", "Room live event delivery is unavailable.");
      }
      if (typeof candidateUnsubscribe.activate !== "function") {
        try {
          candidateUnsubscribe();
        } catch {
          // The invalid subscription cannot be allowed to mask the route error.
        }
        throw invalidEventPortResponse(
          "ROOM_EVENT_PORT_WATERMARK_UNAVAILABLE",
          "Room live event replay watermark delivery is unavailable.",
        );
      }
      if (closed) {
        try {
          candidateUnsubscribe();
        } catch {
          // The request was already closed; no live stream remains to protect.
        }
        if (terminationBeforeHeaders) {
          throw invalidEventPortResponse(
            "ROOM_EVENT_SERVICE_TERMINATED",
            "The project Room live event service ended before the stream opened.",
          );
        }
        return;
      }
      unsubscribe = candidateUnsubscribe;
      if (candidateUnsubscribe.closed !== undefined) {
        void candidateUnsubscribe.closed.then(
          () => {
            if (closed) return;
            if (!res.headersSent) {
              terminationBeforeHeaders = true;
              cleanup();
              return;
            }
            terminateStream("stream_disconnected");
          },
          () => {
            if (closed) return;
            if (!res.headersSent) {
              terminationBeforeHeaders = true;
              cleanup();
              return;
            }
            terminateStream("stream_disconnected");
          },
        );
      }
      const candidateUnsubscribeTermination = liveEventPort.subscribeTermination(
        streamScope,
        terminateForLiveEventTermination,
      );
      if (typeof candidateUnsubscribeTermination !== "function") {
        throw invalidEventPortResponse(
          "ROOM_EVENT_PORT_TERMINATION_INVALID",
          "Room live event termination delivery is unavailable.",
        );
      }
      if (closed) {
        try {
          candidateUnsubscribeTermination();
        } catch {
          // The request was already closed; no live stream remains to protect.
        }
        if (terminationBeforeHeaders) {
          throw invalidEventPortResponse(
            "ROOM_EVENT_SERVICE_TERMINATED",
            "The project Room live event service ended before the stream opened.",
          );
        }
        return;
      }
      unsubscribeTermination = candidateUnsubscribeTermination;

      const replay = normalizeReplay(
        await liveEventPort.reconnect({
          projectId: streamScope.projectId,
          roomId: streamScope.roomId,
          afterCursor,
          limit: query.limit ?? ROOM_EVENT_REPLAY_LIMIT,
        }),
        streamScope,
        afterCursor,
      );
      if (closed) {
        if (terminationBeforeHeaders) {
          throw invalidEventPortResponse(
            "ROOM_EVENT_SERVICE_TERMINATED",
            "The project Room live event service ended before the stream opened.",
          );
        }
        return;
      }

      res.setHeader("Content-Type", "text/event-stream");
      res.setHeader("Cache-Control", "no-cache");
      res.setHeader("Connection", "keep-alive");
      res.setHeader("X-Accel-Buffering", "no");
      res.flushHeaders();
      const connectionWrite = writeRoomSse(res, "room.connection", {
        contractVersion: 1,
        type: "room_connection",
        scope: cloneScope(replay.scope),
        cursor: replay.nextCursor,
        connection: replay.connection,
        alerts: replay.alerts,
      });
      if (connectionWrite !== "ok") {
        if (connectionWrite === "backpressure") terminateBackpressuredStream();
        else terminateStream("stream_disconnected");
        return;
      }
      for (const event of replay.events) {
        if (!emitVerifiedEvent(event)) return;
      }
      if (replay.hasMore) {
        const continuationWrite = writeRoomSse(res, "room.replay.continue", {
          contractVersion: 1,
          type: "room_replay_continue",
          scope: cloneScope(replay.scope),
          cursor: replay.nextCursor,
        }, replay.nextCursor ?? undefined);
        if (continuationWrite !== "ok") {
          if (continuationWrite === "backpressure") terminateBackpressuredStream();
          else terminateStream("stream_disconnected");
          return;
        }
        cleanup();
        if (!res.writableEnded && !res.destroyed) res.end();
        return;
      }

      phase = "live";
      if (closed) return;
      if (!candidateUnsubscribe.activate(replay.nextCursor)) {
        terminateStream("canonical_replay_invalid");
        return;
      }

      heartbeat = setInterval(() => {
        if (closed) return;
        const heartbeatWrite = writeRoomSseFrame(res, ": heartbeat\n\n");
        if (heartbeatWrite === "backpressure") terminateBackpressuredStream();
        else if (heartbeatWrite !== "ok") cleanup();
      }, 30_000);
      heartbeat.unref?.();
      connectionLifetimeTimer = setTimeout(() => {
        if (!closed) terminateStream("stream_disconnected");
      }, maxLiveEventConnectionLifetimeMs);
      connectionLifetimeTimer.unref?.();
    } catch (error) {
      const headersSent = res.headersSent;
      cleanup();
      if (headersSent) {
        if (!res.writableEnded && !res.destroyed) res.end();
        return;
      }
      rethrowRouteError(context, error);
    }
  });

